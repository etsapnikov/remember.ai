package ai.prinim.prinyal.domain

/**
 * Кто есть кто: имена одного человека (Д-30, груминг 1.1).
 *
 * Механика доспроса написана ещё в 1.0.1 и за две недели не сработала **ни
 * разу**. Причина не в порогах: «Саня Иванов», «Саша Иванов» и «Сан Саныч»
 * заводили три строки со счётчиком 1, порог в два упоминания не брался никогда.
 *
 * Здесь два разных вопроса, и их важно не смешивать:
 *
 *  - **что считать одним именем** — «Юля» и «Юле» это одно, и решает это код,
 *    молча;
 *  - **что считать одним человеком** — «Саня Иванов» и «Саша Иванов» может быть
 *    один, а может быть двое, и решает это **человек**. Продукт только
 *    спрашивает, и то лишь когда совпала фамилия: без неё догадка ничем не
 *    подкреплена.
 */
object PersonIdentity {

    /**
     * Ключ имени: падежи и регистр не различаем.
     *
     * Отбрасываем русское окончание, как в поиске по словам, — «Юля», «Юлю»,
     * «Юле» дают один ключ. Фамилию и имя держим порознь: «Иванов» и «Иванова»
     * это чаще всего разные люди одной семьи, и склеивать их молча нельзя.
     */
    fun norm(name: String): String = name.trim().lowercase()
        .split(Regex("\\s+"))
        .joinToString(" ") { stem(it) }

    private fun stem(word: String): String =
        word.trimEnd('а', 'я', 'о', 'е', 'ы', 'и', 'у', 'ю', 'й', 'ь').ifEmpty { word }

    /**
     * Стоит ли спросить, не один ли это человек.
     *
     * Спрашиваем **только при совпавшей фамилии** — так решено дизайнером
     * (Д-30). «Саня Иванов» и «Саша Иванов» вопрос заслуживают; «Саня» и «Саша»
     * порознь — нет, иначе продукт начнёт свататься к каждому созвучию.
     *
     * Одиночные имена без фамилии не сравниваем вовсе: «Вера» и «Валера»
     * похожи ровно настолько, насколько похожи любые два русских имени.
     */
    fun mayBeSame(a: String, b: String): Boolean {
        val left = parts(a)
        val right = parts(b)
        if (left.surname == null || right.surname == null) return false
        if (left.surname != right.surname) return false
        // Фамилия совпала, а имя — нет: это и есть случай, ради которого
        // вопрос заведён. Совпало всё — это одна и та же строка, спрашивать
        // нечего.
        return left.first != right.first
    }

    private data class Parts(val first: String, val surname: String?)

    private fun parts(name: String): Parts {
        val words = norm(name).split(" ").filter { it.isNotBlank() }
        return when (words.size) {
            0 -> Parts("", null)
            1 -> Parts(words[0], null)
            // Фамилия — последнее слово: «Саня Иванов», «Эмиль Шакиров».
            else -> Parts(words.first(), words.last())
        }
    }

    /**
     * Встречается ли имя в тексте **целым словом**.
     *
     * Проверка по основе без границ слова даёт мусор: замер по живому корпусу
     * дал «Вера — 13 заметок», из которых одиннадцать оказались словами
     * «верну» и «проверить». На таком сигнале раздел «Люди» показывал бы
     * выдумку.
     */
    fun mentions(text: String, name: String): Boolean {
        val first = name.trim().split(Regex("\\s+")).firstOrNull()?.lowercase() ?: return false
        if (first.length < MIN_NAME) return false
        val base = stem(first)
        if (base.length < MIN_STEM) return false
        return Regex("\\b${Regex.escape(base)}($ENDINGS)\\b").containsMatchIn(text.lowercase())
    }

    /**
     * Падежные окончания имени — перечислены, а не «любые три буквы».
     *
     * Свободный хвост пропускал глаголы: «верну» — это «вер» плюс «ну», и
     * проверка считала его именем Вера. Окончания у русского имени наперечёт,
     * и перечислить их дешевле, чем ловить каждый глагол отдельно.
     */
    private val ENDINGS = listOf(
        "", "а", "я", "у", "ю", "е", "ы", "и", "ой", "ей", "ою", "ею", "ом", "ем",
        "ов", "ова", "ову", "овы", "ым", "ых", "ами",
    ).joinToString("|")

    /** Короче — не имя, а обрывок распознавания. */
    private const val MIN_NAME = 3

    /** Основа короче трёх букв совпадёт с чем угодно. */
    private const val MIN_STEM = 3

    /** Порог показа человека: две **разные** записи (Д-26). */
    const val MIN_NOTES = 2
}
