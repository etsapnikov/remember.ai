package ai.prinim.prinyal.asr

/**
 * Что именно воркерам нужно от распознавания: превратить сэмплы в текст.
 *
 * Интерфейс ради тестов, и ради вполне конкретных. Путь захвата — «наговорил →
 * появилось в ленте» — собирает вызов модели из транскрипта: по нему ищутся
 * похожие записи, по нему назначается раздел. Ровно здесь три недели молча жила
 * поломка связей: воркер брал заметку из базы **до** распознавания, и все
 * последующие шаги работали с пустым текстом.
 *
 * Проверить это можно только пройдя путь в боевом порядке — сначала пустая
 * заметка, потом текст. Подсунуть транскрипт заранее нельзя: тест обойдёт ту
 * самую ошибку, которую должен ловить. А гонять в каждом тесте настоящие 310 МБ
 * весов — это минуты на прогон и невозможность собрать на машине без модели.
 */
fun interface SpeechToText {
    /** @param samples моно PCM 16 кГц в диапазоне [-1, 1] */
    fun transcribe(samples: FloatArray): String
}
