package ai.prinim.prinyal.ui.theme

import androidx.compose.foundation.clickable
import androidx.compose.foundation.layout.padding
import androidx.compose.material3.minimumInteractiveComponentSize
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp

/**
 * Зона нажатия у слов-кнопок.
 *
 * В продукте почти нет кнопок в обычном смысле: «сделано», «не надо»,
 * «Поправить», «Дописать» — это подписи с обработчиком нажатия. Так задумано:
 * заливка и обводка здесь были бы шумом. Но у подписи зона касания равна
 * **прямоугольнику букв**, и на живом экране она оказалась от 12 до 48 dp у
 * одного и того же органа: где вокруг случайно был отступ строки, зона выросла;
 * где отступа не было — осталась по глифам. Попасть пальцем удавалось в
 * зависимости от того, какая заметка попалась.
 *
 * Порядок модификаторов здесь несущий и неочевидный. `clickable` стоит
 * **перед** `padding`: тогда отступ попадает внутрь зоны и расширяет её. В
 * обратном порядке отступ оказался бы снаружи и зона осталась бы прежней —
 * ошибка, которую не видно ни в коде, ни на экране, только пальцем.
 */
object Touch {

    /** Норма Android. Меньше — промахи, и это измеримо, а не вкусовщина. */
    const val MIN_DP = 48

    /** Горизонтальный запас: слово в четыре буквы иначе остаётся узкой мишенью. */
    const val PAD_DP = 6
}

/**
 * Нажимаемая подпись: зона не меньше 48 dp, вид прежний.
 *
 * `minimumInteractiveComponentSize` — платформенный способ: он резервирует
 * 48 dp вокруг центра элемента, не трогая ни кегль, ни цвет, ни выравнивание
 * текста. Строка становится выше — это цена, которую владелец и просил
 * заплатить.
 */
fun Modifier.tap(enabled: Boolean = true, onClick: () -> Unit): Modifier =
    this
        .minimumInteractiveComponentSize()
        // Здесь именно clickable, а не tap: массовая замена по проекту однажды
        // переписала эту строку саму на себя, и `tap` начал вызывать `tap` —
        // приложение падало со StackOverflow при открытии ленты. Автозамена не
        // отличает определение от применения.
        .clickable(enabled = enabled, onClick = onClick)
        .padding(horizontal = Touch.PAD_DP.dp)
