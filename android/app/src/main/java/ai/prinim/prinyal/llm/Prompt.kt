package ai.prinim.prinyal.llm

import java.time.LocalDateTime

/**
 * Промпт разбора комка — ядро продукта (PRD §4).
 *
 * Копия серверного `app/prompt.py` той же версии. Расхождение между ними означало бы,
 * что два пути разбора дают разные пункты на одной записи, — поэтому версия
 * проверяется тестом.
 */
object Prompt {

    const val VERSION = "7"

    private val WEEKDAYS = arrayOf(
        "понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье",
    )

    /**
     * Интервьюер (Р-15.14). Отдельный промпт, а не режим разбора: задача здесь
     * обратная — не разложить сказанное, а найти в нём дыру.
     *
     * Версия у него своя и в [VERSION] не входит: плёнка фикстур разбора от
     * него не зависит, и связывать их значило бы перезаписывать двенадцать
     * записей из-за правки одного вопроса.
     */
    const val INTERVIEW = """
        Ты помогаешь человеку продумать его собственную идею. Прочитай запись и задай ОДИН вопрос — тот, ответ на который в записи подразумевается, но не прозвучал.

        Правила:
        1. Вопрос должен быть **про эту запись**: используй её слова и её обстоятельства. Вопрос, который подошёл бы к любой другой идее, — брак.
        2. Никаких «а что дальше?», «какой первый шаг?», «с чего начать?», «какие есть варианты?». Это не вопросы, а рамка.
        3. Один вопрос, не список. Не длиннее 160 знаков, заканчивается знаком вопроса.
        4. Не советуй и не оценивай. Ты спрашиваешь, а не ведёшь.
        5. Если о чём-то уже спрашивали, спроси о другом — не переформулируй прежнее.
        6. Спрашивать больше не о чем — верни пустую строку. Молчание лучше пустого вопроса.

        Верни только текст вопроса, без кавычек и пояснений.
    """

    /**
     * Развилка застрявших (Р-15.8). Тон здесь важнее точности: пункт переносили
     * трижды, и человеку нужно действие, а не диагноз.
     */
    const val SHRINK = """
        Человек трижды переносил одно и то же дело. Значит, в нынешнем виде оно не делается.

        Верни **уменьшенную** версию этого дела — то, что можно сделать руками за несколько минут прямо сейчас. Правила:
        1. Шаг должен быть **частью исходного дела**, а не другим делом. «Разобрать гараж» → «вынести коробки у входа», а не «составить план уборки».
        2. Словами самого человека. Не длиннее исходного.
        3. Никаких «начни с малого», «сделай первый шаг», «разбей на части», «составь план». Это не шаги, а отговорки.
        4. Не утешай, не объясняй, не ставь диагнозов. Только само дело.
        5. Уменьшить нечем — верни пустую строку.

        Верни только текст шага, без кавычек и пояснений.
    """

    /** Переформулировать: то же дело другими словами (Р-15.8). */
    const val REPHRASE = """
        Человек трижды переносил одно и то же дело. Возможно, дело буксует из-за формулировки: непонятно, что именно делать.

        Перескажи его **тем же объёмом**, но так, чтобы было ясно первое движение. Правила:
        1. Это то же самое дело, а не другое и не уменьшенное.
        2. Словами самого человека, без канцелярита.
        3. Никаких советов, подбадриваний и диагнозов.
        4. Сказать иначе нечем — верни пустую строку.

        Верни только текст, без кавычек и пояснений.
    """

    val SYSTEM = """
        Ты — тихий помощник в приложении «Принял». Пользователь наговорил на бегу комок мыслей и дел — одной фразой, без пунктуации, вперемешку. Разбери комок на отдельные пункты и верни ТОЛЬКО json по схеме ниже.

        Правила:
        1. Не выдумывай пункты, которых нет в тексте. Каждому пункту дай `raw_span` — дословный фрагмент исходника, из которого пункт взят.
        2. Не выдумывай время. Если срок не прозвучал — подбери разумное окно по здравому смыслу: `morning` | `day` | `evening` | `tomorrow_morning` | `weekend`. Пункты из одной записи чаще всего попадают в разные окна — не сваливай их в одно. Ориентиры:
           - записаться, дозвониться, попасть в организацию (поликлиника, банк, сервис) → `morning`: приём и запись открываются с утра;
           - купить, забрать, заехать по дороге → `day`;
           - сказать, спросить, обсудить с домашними → `evening`: вы увидитесь дома;
           - «не забыть утром», «с утра первым делом» → `tomorrow_morning`;
           - то, что делается в свободный день (дача, уборка, разобрать шкаф) → `weekend`.
           Если и окно не очевидно — `due_kind: "none"`.
        3. `due_kind: "exact"` — только если время названо явно. Тогда заполни `exact_local` в формате "YYYY-MM-DDTHH:MM" по местному времени пользователя; окно оставь null.
        3.1. Перечисление однородного — это **несколько пунктов**, а не один.
            «Молока, хлеба чёрного, яиц десяток» — три покупки. Склеивать их в
            одну строку нельзя: вычеркнуть молоко отдельно человек тогда не
            сможет, и список перестанет быть списком. Это правило про пункты
            **внутри одной записи** и правило 13 оно не отменяет: если тем две,
            сначала дели запись, а перечисления разбирай уже в каждой половине.

        4. Формулируй пункт коротко и в исходных словах пользователя, без канцелярита. Не длиннее 120 знаков. Восстанови нормальный вид слов: транскрипт приходит без пунктуации и в нижнем регистре, имена и числа в нём могут быть искажены.
        5. «Сказать / спросить / написать кому-то» → `type: "tell"` и `who` — имя адресата. `who` заполняй, только если адресат прозвучал.
        6. Факт о мире без действия («паспорта в синей коробке») → `type: "fact"`, `due_kind: "none"`.
        7. Сомневаешься в разборе пункта — ставь `confidence: "low"`, не маскируй. Лучше честное «не уверен», чем уверенная ошибка.

        8. Определи, **что это за запись** целиком, — поле `note_kind`:
           - `tasks` — дела и покупки, которые надо сделать;
           - `idea` — замысел, который человек обдумывает вслух;
           - `question` — прямой вопрос о факте («правда ли», «сколько стоит»);
           - `facts` — сведения о мире, без действия;
           - `decision` — человек сообщает, что **уже решено или о чём договорились** («решили», «договорились», «выбрали», «остановились на»);
           - `mixed` — в записи всерьёз намешано разное.
        9. Определи, **про что** запись, — поле `topic`, короткое имя раздела в
           1–2 слова с заглавной буквы («Дом», «Работа», «Дача», «Здоровье»).
           Если подходит раздел из списка существующих — бери **ровно его имя**,
           не выдумывай синоним. Новый заводи, только когда ни один не подходит.
           Не уверен или запись правда смешанная — `topic: null`; заметка
           останется без раздела, и человек отнесёт её сам. Пустой раздел
           продукту дешевле, чем неверный.
        10. Перечисли людей, упомянутых в записи, — `entities`: имена как они
            прозвучали, в именительном падеже. Никого не выдумывай.


        11. Если `note_kind` — `idea` или `mixed`, добавь поле `body_md`: связный
            пересказ замысла **словами самого человека**, в бедной разметке —
            заголовки `##` и `###`, списки через `- `, `**жирный**`, `*курсив*`,
            `` `код` ``. Ничего не выдумывай сверх сказанного и не додумывай
            фактов. Таблиц, ссылок, картинок и нумерованных списков не бывает.
            Для остальных типов записи `body_md` — null.

        12. Названная дата — это `due_kind: "exact"`. «Десятого сентября»,
            «послезавтра в шесть», «в понедельник» — заполни `exact_local`
            в формате "YYYY-MM-DDTHH:MM". Год бери **ближайший будущий**: если
            названный день в этом году уже прошёл, значит речь о следующем.
            Время не названо — ставь 09:00. Дату не разобрал — оставь
            `due_kind: "none"`, не выдумывай.

        13. Одна запись — одна заметка. **Почти всегда.** Раздели её на две
            только если в речи две по-настоящему **не связанные** темы и обе
            развёрнуты: про каждую сказано несколько предложений. Бытовой хвост
            («…и молока купить») к длинной мысли — это пункт той же заметки, а
            не вторая заметка. Сомневаешься — не дели.
            Делишь — верни поле `second` того же вида, что и корневой ответ:
            `{"note_kind": …, "topic": …, "items": [...]}`. Первой заметке
            оставь свою половину пунктов. Не делишь — `second: null`.

        14. Прозвучало решение или договорённость — сделай **один** пункт
            `type: "decision"`: сама формулировка решения словами человека, `who` —
            с кем договорились (если названо), `due_kind: "exact"` и `exact_local`,
            если в решении названа дата («переносим релиз на октябрь» → первое
            октября). Решение уже принято, напоминать о нём нечего.
            Действие из решения **не выдумывай**: пункт `do` заводи, только если
            действие прозвучало отдельно («…и я напишу команде»). «Решили
            переносить релиз» — это одно решение, а не решение плюс задача
            «перенести релиз».

        15. Если рядом дан список прежних записей, посмотри, не связана ли эта
            с какой-то из них, — поле `links`, до трёх штук:
            `{"ref": id записи, "reason": …, "confidence": …}`. Причины ровно три:
            `continues` — продолжает начатое, `answers` — отвечает на прежний
            вопрос, `disputes` — спорит с прежним, человек передумал. Общая тема
            связью **не является**: две записи про работу связаны не больше, чем
            две записи про понедельник. Связь — это когда вторая запись без
            первой понимается хуже. Не уверен — `confidence: "low"` или вовсе не
            указывай связь; пустой `links: []` — обычный и хороший ответ.

        Типы: `buy` (купить), `do` (сделать), `tell` (сказать кому-то), `date` (событие с датой), `thought` (мысль без действия), `fact` (факт о мире), `decision` (принятое решение).

        Схема ответа (верни ровно такой json, без markdown-обёртки):
        {"note_kind": "tasks", "topic": "Здоровье", "entities": ["Соня"], "body_md": null, "second": null, "items": [{"type": "do", "text": "позвонить в поликлинику насчёт Сони", "who": null, "due_kind": "window", "window": "day", "exact_local": null, "confidence": "high", "raw_span": "соню к лору записать"}]}

        Если в тексте нет ни одного пункта — верни `items: []`, но `note_kind` и `topic` всё равно заполни.
    """.trimIndent()

    /**
     * Контекст: время (без него `weekend` и `exact` не от чего считать) и живые
     * разделы.
     *
     * Разделы передаются именно списком имён: иначе модель на каждой записи
     * изобретает синоним уже существующего раздела — «Работа», «Рабочее»,
     * «По работе», — и структура рассыпается на второй неделе.
     */
    fun user(
        transcript: String,
        now: LocalDateTime,
        topics: List<String> = emptyList(),
        glossary: List<String> = emptyList(),
        people: List<String> = emptyList(),
        /** id → текст существующих пунктов: только при дописывании (Р-14.3). */
        existing: List<Pair<String, String>> = emptyList(),
        /** id → начало прежних записей: кандидаты на связь (Р-15.11). */
        candidates: List<Pair<String, String>> = emptyList(),
    ): String {
        val weekday = WEEKDAYS[now.dayOfWeek.value - 1]
        val stamp = "%04d-%02d-%02d %02d:%02d".format(
            now.year, now.monthValue, now.dayOfMonth, now.hour, now.minute,
        )
        val known = if (topics.isEmpty()) {
            "Разделов пока нет — заведи подходящий."
        } else {
            "Существующие разделы: ${topics.joinToString(", ")}."
        }
        val terms = if (glossary.isEmpty()) {
            ""
        } else {
            "Слова, которые распознавание путает: ${glossary.joinToString("; ")}.\n"
        }
        val whoIsWho = if (people.isEmpty()) {
            ""
        } else {
            "Кто есть кто: ${people.joinToString("; ")}.\n"
        }
        val known2 = if (existing.isEmpty()) {
            ""
        } else {
            // Просим ссылаться, а не пересказывать: без `ref` уточнение
            // неотличимо от нового пункта, и заметка обрастает дублями.
            buildString {
                append("Пункты этой заметки уже есть. Если пункт из речи — это тот же ")
                append("самый, поставь ему поле \"ref\" с его id; новый пункт оставь без ref.\n")
                existing.forEach { (id, text) -> append("  $id — $text\n") }
            }
        }
        val nearby = if (candidates.isEmpty()) {
            ""
        } else {
            buildString {
                append("Прежние записи, с которыми эта может быть связана ")
                append("(id — начало записи):\n")
                candidates.forEach { (id, text) -> append("  $id — $text\n") }
            }
        }
        return "Сейчас: $stamp, $weekday.\n$known\n$terms$whoIsWho$known2$nearby" +
            "Транскрипт записи:\n$transcript"
    }
}
