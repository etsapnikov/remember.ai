package ai.prinim.prinyal.domain

import ai.prinim.prinyal.data.DueKind
import ai.prinim.prinyal.data.ItemType

/**
 * Кому продукт возвращается, а кому нет.
 *
 * Правило вынесено из планировщика в отдельную функцию не ради красоты, а чтобы
 * его можно было проверить в одиночку. Внутри `planReturn` оно жило бы за
 * базой, аларм-менеджером и часами — то есть проверялось бы только целиком, а
 * значит редко.
 */
object ReturnPolicy {

    /**
     * @return планировать ли возврат по этому пункту
     */
    fun schedules(type: ItemType, dueKind: DueKind): Boolean {
        // Решение уже принято, напоминать о нём нечего. Дата у решения при этом
        // остаётся и показывается: «релиз в октябре» полезно видеть, но не
        // полезно получать уведомлением в ночь на первое (Р-15.10).
        if (type == ItemType.DECISION) return false
        // Факт о мире — не дело: «паспорта в синей коробке» ждёт вопроса, а не
        // напоминания.
        return dueKind != DueKind.NONE
    }
}
