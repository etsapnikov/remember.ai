package ai.prinim.prinyal.ui.theme

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.runtime.Immutable
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/** Шкала отступов из токенов (`space`). База 4, шаг не «на глаз». */
@Immutable
/**
 * Лестница отступов — одна на весь продукт (полишинг, п. 4).
 *
 * Каждая версия приносила своё расстояние: лента считала на 32 и 12, списки на
 * 15, «Дни» на 16, блоки карточки на 22–26. По отдельности все числа были
 * правы, вместе они не складывались в шкалу — и экраны «между» начинали
 * импровизировать.
 *
 * Шесть ступеней, и у каждой своя работа. Плотность задаётся не размером
 * отступа, а **числом ступеней, которые экран использует**: список живёт на
 * двух и потому плотный, лента на четырёх и потому дышит. Больше четырёх
 * ступеней на экран — уже неопрятность.
 */
object Space {
    /** Текст и его собственная мета-строка — они одно целое. */
    val xs: Dp = 4.dp

    /** Заголовок и то, что под ним. */
    val s: Dp = 8.dp

    /** Однородные элементы внутри группы — пункты одной записи. */
    val sm: Dp = 12.dp

    /** Строки списка с хайрлайном и блоки внутри карточки. */
    val m: Dp = 16.dp

    /** Смысловые части экрана: шапка ↔ содержимое, блок ↔ блок. */
    val ml: Dp = 24.dp

    /** Записи в ленте — единственное место, где нужен воздух-разделитель. */
    val l: Dp = 32.dp
    val xl: Dp = 32.dp
    val xxl: Dp = 44.dp

    /** Поле экрана — 18 на всех поверхностях (полишинг, п. 4). */
    val screen: Dp = 18.dp
    val itemGap: Dp = 18.dp
}

/** Радиусы из токенов (`radius`). Лист почти не скруглён — он бумажный, не пластиковый. */
@Immutable
object Radius {
    val sheet = RoundedCornerShape(2.dp)
    val control = RoundedCornerShape(12.dp)
    val pill = RoundedCornerShape(999.dp)
    val icon = RoundedCornerShape(20.dp)
}

/** Геометрия клавиши записи (`key`): корпус, колпачок, нажатый колпачок, точка. */
@Immutable
object KeyMetrics {
    val housing: Dp = 112.dp
    val cap: Dp = 84.dp
    val capPressed: Dp = 78.dp
    /**
     * Радиус колпачка. Его не было в токенах вовсе, и форму ничто не удерживало —
     * колпачок незаметно стал кругом (аудит Д-7, п. 11).
     */
    val capRadius: Dp = 26.dp
    /** Ход колпачка вниз при нажатии (R1.2 §12). */
    val capDrop: Dp = 4.dp
    val dot: Dp = 26.dp
}

/**
 * Минимальная цель касания. Ключевые действия — в нижней трети экрана, управление
 * одной рукой (ТЗ UI §2, п. 6).
 */
val MinTouchTarget: Dp = 48.dp
