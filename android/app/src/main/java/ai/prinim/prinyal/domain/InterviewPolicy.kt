package ai.prinim.prinyal.domain

/**
 * Интервьюер: «покрутить» идею (Р-15.14).
 *
 * Продукт задаёт **один** вопрос за раз и только по тому, что человек уже
 * сказал. Это не беседа и не коучинг: цель — вытащить из идеи то, что в ней
 * подразумевалось, но не прозвучало.
 *
 * Генерик-вопрос здесь — брак, а не слабый результат. «А что дальше?» и «Какой
 * первый шаг?» можно задать о чём угодно, не прочитав ни строчки; получив
 * такой вопрос, человек справедливо решит, что его не слушали, и режим больше
 * не откроет. Лучше не спросить ничего.
 *
 * Отсюда две проверки, обе обязательные: вопрос не из стоп-листа и вопрос
 * **опирается на слова самой идеи**. Вторая грубая — совпадение основ, — но она
 * ловит именно тот случай, ради которого заведена: вопрос, который подошёл бы
 * к любой другой записи.
 */
object InterviewPolicy {

    /** Сколько слов идеи должно прозвучать в вопросе, чтобы он был про неё. */
    private const val MIN_ECHO = 1

    /** Короче — не вопрос, а междометие. */
    private const val MIN_CHARS = 12

    /** Длинный вопрос перестаёт быть одним вопросом. */
    const val MAX_CHARS = 160

    /**
     * Годится ли вопрос.
     *
     * @param question что предложила модель
     * @param idea текст идеи — транскрипт и всё, что дописано
     * @param asked о чём уже спрашивали в этой заметке
     */
    fun accepts(question: String, idea: String, asked: List<String> = emptyList()): Boolean {
        val clean = question.trim()
        if (clean.length !in MIN_CHARS..MAX_CHARS) return false
        if (!clean.endsWith("?")) return false

        val lower = clean.lowercase()
        if (GENERIC.any { lower.contains(it) }) return false

        val words = stems(clean)
        val ideaWords = stems(idea) - COMMON

        // Повтор считаем **только по словам, которых в идее не было**.
        //
        // Первая версия сличала вопросы целиком — и на живом прогоне забраковала
        // третий круг подряд: вопросы про одну идею неизбежно делят её же
        // словарь («приложение», «заметки», «контекст»), а требование опираться
        // на слова идеи это ещё и поощряет. Два правила воевали друг с другом.
        // Различает вопросы то, что каждый добавляет от себя.
        // Сравниваем **долю**, а не число: вопросы короткие, и трёх общих слов
        // в них не наберётся даже у почти дословного пересказа.
        val novel = words.filterNot { word -> hits(word, ideaWords) }.toSet()
        if (asked.any { earlier ->
                val earlierNovel = stems(earlier).filterNot { hits(it, ideaWords) }.toSet()
                val common = overlap(novel, earlierNovel)
                val smaller = minOf(novel.size, earlierNovel.size)
                smaller >= REPEAT_MIN && common >= REPEAT_MIN && common * 2 >= smaller
            }
        ) {
            return false
        }

        // Вопрос обязан опираться на слова идеи, а не на общую рамку.
        return overlap(words, ideaWords) >= MIN_ECHO
    }

    /**
     * Сказал ли человек «хватит» — выход из режима словами, а не кнопкой.
     *
     * Совпадение только целиком. «Хватит времени на это не будет» начинается с
     * того же слова, но это ответ, а не команда, и оборвать на нём разговор
     * значит потерять сказанное — цена ошибки здесь несимметрична.
     */
    fun isEnough(answer: String): Boolean {
        val lower = answer.trim().lowercase().trimEnd('.', '!', ',', '?')
        return lower in ENOUGH
    }

    /** Меньше двух общих слов — совпадение, а не пересказ. */
    private const val REPEAT_MIN = 2

    private fun stems(text: String): Set<String> =
        Bm25.tokenize(text).filter { it.length >= 3 }.toSet()

    /**
     * Пересечение по началу слова, а не по равенству.
     *
     * «Файл» и «файлом» — одно слово, и усечения BM25 тут не хватает: оно рубит
     * длинные, но не сближает короткое с длинным. Общее начало в четыре буквы
     * грубее морфологии и иногда ошибётся, но здесь цена ошибки — лишний
     * отброшенный или пропущенный вопрос, а не потеря данных.
     */
    private fun overlap(a: Set<String>, b: Set<String>): Int = a.count { hits(it, b) }

    private fun hits(word: String, others: Set<String>): Boolean = others.any { other ->
        // Равенство считается всегда: правило про общее начало в четыре буквы
        // придумано для длинных слов и молча выбрасывало короткие — «что» не
        // совпадало даже само с собой, и почти дословный пересказ проходил.
        if (word == other) return@any true
        val shared = word.commonPrefixWith(other).length
        shared >= ECHO_PREFIX && shared >= minOf(word.length, other.length)
    }

    private const val ECHO_PREFIX = 4

    /**
     * Вопросы, которые подошли бы к любой записи. Тот же список, что в eval
     * яруса 2, — расхождение означало бы, что стенд проверяет не то правило.
     */
    private val GENERIC = listOf(
        "что дальше",
        "какой первый шаг",
        "с чего начать",
        "что для этого нужно",
        "как ты это видишь",
        "что думаешь",
        "зачем тебе это",
        "какие есть варианты",
    )

    /** Слова рамки: их совпадение о связи с идеей не говорит. */
    private val COMMON = setOf(
        "нужн", "надо", "может", "будет", "хочу", "думаю", "просто", "очень", "тоже", "потом",
    )

    private val ENOUGH = listOf("хватит", "стоп", "достаточно", "всё", "закончили", "не надо")
}
