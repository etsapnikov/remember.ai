package ai.prinim.prinyal.domain

/**
 * Голосовые команды над корпусом (Р-15.13).
 *
 * Пока команда ровно одна — «собери контекст по …». Важна не она, а граница:
 * команда **не заметка**, и записывать её в ленту нельзя. Иначе от каждой
 * попытки собрать пак остаётся запись «собери контекст по авторизации», которую
 * человек потом удаляет руками, — продукт превращает свою же функцию в мусор.
 *
 * Детект нарочно узкий: глагол в начале плюс предлог. Широкий детект опаснее —
 * он съест настоящую заметку, которая начинается со слова «собери» («собери
 * рюкзак на дачу»), и человек потеряет сказанное. Ошибиться в эту сторону
 * значит потерять данные, в обратную — просто не сработать.
 */
object VoiceCommand {

    data class Pack(val topic: String)

    private val PATTERN = Regex(
        """^\s*(?:собери|собрать|подготовь|подготовить)\s+
           (?:мне\s+)?
           (?:контекст|контекст-пак|пак|подборку|выжимку)\s+
           (?:по|про|о|об)\s+
           (.{2,60})$""",
        setOf(RegexOption.IGNORE_CASE, RegexOption.COMMENTS),
    )

    /**
     * @return тема пака **в том падеже, в каком прозвучала**, или null — это
     *         обычная запись. Склонять русские существительные нечем, а
     *         выдуманный именительный был бы догадкой; заголовок пака берётся
     *         из имени раздела, когда он нашёлся по этой теме.
     */
    fun packOf(transcript: String): Pack? {
        val clean = transcript.trim().trimEnd('.', '!', '?')
        val topic = PATTERN.find(clean)?.groupValues?.get(1)?.trim() ?: return null
        // Тема из нескольких слов — уже не тема, а рассказ: скорее всего это
        // обычная запись, просто начатая похоже.
        if (topic.split(Regex("\\s+")).size > MAX_WORDS) return null
        return Pack(topic.trimEnd(',', '.').replaceFirstChar { it.uppercase() })
    }

    private const val MAX_WORDS = 4
}
